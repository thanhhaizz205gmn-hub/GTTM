-- DIGITAL TWIN DATABASE SCHEMA INITIALIZATION (SUPABASE)
-- ====================================================================

-- 1. Create weather_logs table
CREATE TABLE IF NOT EXISTS public.weather_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ DEFAULT NOW(),
    temp DOUBLE PRECISION NOT NULL,
    humidity DOUBLE PRECISION NOT NULL
);

-- 2. Create train_schedules table
CREATE TABLE IF NOT EXISTS public.train_schedules (
    train_id TEXT PRIMARY KEY,
    arrival_time TIME NOT NULL,
    departure_time TIME NOT NULL,
    max_capacity INT DEFAULT 1000 NOT NULL
);

-- 3. Create passenger_density_logs table
CREATE TABLE IF NOT EXISTS public.passenger_density_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMPTZ NOT NULL,
    train_id TEXT NOT NULL,
    passenger_count INT NOT NULL
);

-- 4. Enable Row Level Security (RLS) and grant open access for service_role and anon
ALTER TABLE public.weather_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.train_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.passenger_density_logs ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any to avoid collision
DROP POLICY IF EXISTS "Allow all for weather_logs" ON public.weather_logs;
DROP POLICY IF EXISTS "Allow all for train_schedules" ON public.train_schedules;
DROP POLICY IF EXISTS "Allow all for passenger_density_logs" ON public.passenger_density_logs;

CREATE POLICY "Allow all for weather_logs" ON public.weather_logs FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all for train_schedules" ON public.train_schedules FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all for passenger_density_logs" ON public.passenger_density_logs FOR ALL USING (true) WITH CHECK (true);

-- Notify PostgREST to reload schema cache
NOTIFY pgrst, 'reload schema';
